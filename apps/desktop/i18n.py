def detect():
    """Idioma inicial a partir do sistema (pt como padrão)."""
    candidates = [os.environ.get(name, "") for name in ("LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE")]
    try:
        candidates.append(locale.getlocale()[0] or "")
    except Exception:
        pass
    if os.name == "nt":
        try:
            import ctypes
            candidates.append(locale.windows_locale.get(ctypes.windll.kernel32.GetUserDefaultUILanguage(), ""))
        except Exception:
            pass
    for value in candidates:
        value = value.lower()
        if value.startswith(("pt", "portuguese")): return "pt"
        if value.startswith(("es", "spanish")): return "es"
        if value.startswith(("en", "english")): return "en"
    return "pt"


