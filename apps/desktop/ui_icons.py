def glyph(name, color="#DDD5FF", size=22):
    image = Image.new("RGBA", (96,96))
    draw = ImageDraw.Draw(image)
    for points in PATHS.get(name, PATHS["file"]):
        draw.line([(x*4,y*4) for x,y in points], fill=color, width=7, joint="curve")
    if name in ("info", "history"):
        draw.arc((12,12,84,84), 30 if name=="history" else 0, 325 if name=="history" else 360, fill=color, width=7)
    return image.resize((size,size), Image.Resampling.LANCZOS)
