ALIASES = {"separate": "layers", "karaoke": "mic", "support": "heart"}


@lru_cache(maxsize=512)
def glyph(name, color="#DDD5FF", size=22, stroke=2.0):
    """Renderiza um ícone RGBA. `stroke` segue a espessura da grade 24×24."""
    scale = 16
    canvas = 24 * scale
    image = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    width = max(1, round(stroke * scale))
    half = width / 2
    s = lambda v: v * scale

    def cap(x, y):
        draw.ellipse((s(x) - half, s(y) - half, s(x) + half, s(y) + half), fill=color)

    for op in ICONS.get(ALIASES.get(name, name), ICONS["file"]):
        kind = op[0]
        if kind == "l":
            points = [(s(x), s(y)) for x, y in op[1]]
            draw.line(points, fill=color, width=width, joint="curve")
            for x, y in op[1]:
                cap(x, y)
        elif kind == "c":
            _, cx, cy, r = op
            draw.ellipse((s(cx - r) - half, s(cy - r) - half, s(cx + r) + half, s(cy + r) + half), outline=color, width=width)
        elif kind == "a":
            _, cx, cy, r, start, end = op
            if start == end:  # meridiano do globo
                draw.ellipse((s(cx - r * .45) - half, s(cy - r) - half, s(cx + r * .45) + half, s(cy + r) + half), outline=color, width=width)
                continue
            box = (s(cx - r) - half, s(cy - r) - half, s(cx + r) + half, s(cy + r) + half)
            draw.arc(box, start, end, fill=color, width=width)
            import math
            for angle in (start, end):
                rad = math.radians(angle)
                cap(cx + r * math.cos(rad), cy + r * math.sin(rad))
        elif kind == "r":
            _, x0, y0, x1, y1, radius = op
            draw.rounded_rectangle((s(x0), s(y0), s(x1), s(y1)), radius=s(radius), outline=color, width=width)
        elif kind == "d":
            _, cx, cy, r = op
            draw.ellipse((s(cx - r), s(cy - r), s(cx + r), s(cy + r)), fill=color)
        elif kind == "m":  # lua crescente: dois círculos, cada arco só onde fica fora/dentro do outro
            import math
            c1, r1, c2, r2 = (12, 12), 9, (17.2, 6.8), 7
            for center, radius, keep in ((c1, r1, lambda p: math.dist(p, c2) >= r2), (c2, r2, lambda p: math.dist(p, c1) <= r1)):
                pts = [(center[0] + radius * math.cos(math.radians(a / 2)), center[1] + radius * math.sin(math.radians(a / 2))) for a in range(721)]
                for p0, p1 in zip(pts, pts[1:]):
                    if keep(p0) and keep(p1):
                        draw.line([(s(p0[0]), s(p0[1])), (s(p1[0]), s(p1[1]))], fill=color, width=width)
                        cap(*p1)
        elif kind == "p":
            draw.polygon([(s(x), s(y)) for x, y in op[1]], fill=color)
    return image.resize((size * 4, size * 4), Image.Resampling.LANCZOS)
